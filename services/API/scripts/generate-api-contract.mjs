import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const serviceRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = resolve(serviceRoot, '../..');
const contractPath = resolve(serviceRoot, 'amplify/functions/api/api-contract.json');
const outputPath = resolve(repositoryRoot, 'packages/heytim-contract/src/api-contract.generated.ts');
const openApiOutputPath = resolve(repositoryRoot, 'packages/heytim-contract/openapi.generated.json');
const swiftOutputPath = resolve(
  repositoryRoot,
  'apps/iOS/Sources/HeyTimCore/APIRoutes.generated.swift',
);
const contract = JSON.parse(readFileSync(contractPath, 'utf8'));

if (contract.version !== 1 || !Array.isArray(contract.routes)) {
  throw new Error('Unsupported API contract');
}

const methods = new Set(['GET', 'POST', 'PUT', 'DELETE', 'PATCH']);
const accessModes = new Set(['public', 'authenticated']);
const routeIds = new Set();
const routeKeys = new Set();
const validatedRoutes = contract.routes.map((route) => {
  const fields = ['id', 'method', 'path', 'access', 'handler'];
  if (!route || fields.some((field) => typeof route[field] !== 'string' || !route[field])) {
    throw new Error('Invalid API contract route');
  }
  if (!methods.has(route.method) || !accessModes.has(route.access)) {
    throw new Error(`Unsupported API contract route: ${route.id}`);
  }
  const routeKey = `${route.method} ${route.path}`;
  if (routeIds.has(route.id) || routeKeys.has(routeKey)) {
    throw new Error(`Duplicate API contract route: ${route.id}`);
  }
  routeIds.add(route.id);
  routeKeys.add(routeKey);
  return route;
});
const entries = validatedRoutes.map((route) => `  ${JSON.stringify(route.id)}: ${JSON.stringify(route.path)},`);
const output = [
  '// Generated by services/API/scripts/generate-api-contract.mjs. Do not edit directly.',
  'export const apiContractPaths = {',
  ...entries,
  '} as const;',
  '',
].join('\n');

const swiftString = (value) => JSON.stringify(value)
  .replaceAll('\\/', '/')
  .replaceAll('\\b', '\\u{0008}')
  .replaceAll('\\f', '\\u{000c}');
const swiftCases = validatedRoutes.map((route) => `    case ${route.id}`);
const swiftRoutes = validatedRoutes.map((route) => [
  `        .${route.id}: APIContractRoute(`,
  `            id: .${route.id},`,
  `            method: .${route.method.toLowerCase()},`,
  `            pathTemplate: ${swiftString(route.path)},`,
  `            access: .${route.access === 'public' ? 'publicAccess' : route.access}`,
  '        ),',
].join('\n'));
const swiftOutput = [
  '// Generated by services/API/scripts/generate-api-contract.mjs. Do not edit directly.',
  'import Foundation',
  '',
  'public enum APIAccess: String, Sendable {',
  '    case publicAccess = "public"',
  '    case authenticated',
  '}',
  '',
  'public enum HTTPMethod: String, Sendable {',
  '    case get = "GET"',
  '    case post = "POST"',
  '    case put = "PUT"',
  '    case delete = "DELETE"',
  '    case patch = "PATCH"',
  '}',
  '',
  'public enum APIRouteID: String, CaseIterable, Sendable {',
  ...swiftCases,
  '}',
  '',
  'public enum APIContractError: Error, Equatable, Sendable {',
  '    case unknownRoute(APIRouteID)',
  '    case missingPathParameter(String)',
  '    case invalidPathParameter(String)',
  '}',
  '',
  'public struct APIContractRoute: Sendable {',
  '    public let id: APIRouteID',
  '    public let method: HTTPMethod',
  '    public let pathTemplate: String',
  '    public let access: APIAccess',
  '',
  '    public func path(',
  '        parameters: [String: String] = [:],',
  '        queryItems: [URLQueryItem] = []',
  '    ) throws -> String {',
  '        var result = pathTemplate',
  '        let expression = try NSRegularExpression(pattern: #"\\{([^}]+)\\}"#)',
  '        let matches = expression.matches(',
  '            in: result,',
  '            range: NSRange(result.startIndex..., in: result)',
  '        ).reversed()',
  '        var pathAllowed = CharacterSet.urlPathAllowed',
  '        pathAllowed.remove(charactersIn: "/?#")',
  '        for match in matches {',
  '            guard let nameRange = Range(match.range(at: 1), in: result) else { continue }',
  '            let name = String(result[nameRange])',
  '            guard let value = parameters[name] else {',
  '                throw APIContractError.missingPathParameter(name)',
  '            }',
  '            guard let encoded = value.addingPercentEncoding(withAllowedCharacters: pathAllowed),',
  '                  let matchRange = Range(match.range(at: 0), in: result)',
  '            else { throw APIContractError.invalidPathParameter(name) }',
  '            result.replaceSubrange(matchRange, with: encoded)',
  '        }',
  '        guard !queryItems.isEmpty else { return result }',
  '        var components = URLComponents()',
  '        components.percentEncodedPath = result',
  '        components.queryItems = queryItems',
  '        guard let encoded = components.url?.absoluteString else { return result }',
  '        return encoded',
  '    }',
  '}',
  '',
  'public enum GeneratedAPIContract {',
  '    public static let routes: [APIRouteID: APIContractRoute] = [',
  ...swiftRoutes,
  '    ]',
  '',
  '    public static func route(_ id: APIRouteID) throws -> APIContractRoute {',
  '        guard let route = routes[id] else { throw APIContractError.unknownRoute(id) }',
  '        return route',
  '    }',
  '}',
  '',
].join('\n');

const openApiPaths = {};
for (const route of validatedRoutes) {
  const parameters = [...route.path.matchAll(/\{([^}]+)\}/g)].map((match) => ({
    name: match[1],
    in: 'path',
    required: true,
    schema: { type: 'string', minLength: 1, maxLength: 256 },
  }));
  const operation = {
    operationId: route.id,
    tags: [route.handler],
    ...(route.access === 'authenticated' ? { security: [{ cognitoBearer: [] }] } : { security: [] }),
    ...(parameters.length ? { parameters } : {}),
    ...(['POST', 'PUT', 'PATCH'].includes(route.method) ? {
      requestBody: {
        required: false,
        content: {
          'application/json': { schema: { type: 'object', additionalProperties: true } },
        },
      },
    } : {}),
    responses: {
      200: {
        description: 'Successful response',
        content: {
          'application/json': { schema: { type: ['object', 'array'], additionalProperties: true } },
        },
      },
      default: {
        description: 'Stable HeyTim API error',
        content: {
          'application/json': { schema: { $ref: '#/components/schemas/ApiError' } },
        },
      },
    },
  };
  openApiPaths[route.path] ??= {};
  openApiPaths[route.path][route.method.toLowerCase()] = operation;
}
const openApi = `${JSON.stringify({
  openapi: '3.1.0',
  info: {
    title: 'HeyTim API',
    version: String(contract.version),
    description: 'Generated route and authentication contract. Domain schemas remain additive.',
  },
  'x-heytim-contract-version': contract.version,
  paths: openApiPaths,
  components: {
    securitySchemes: {
      cognitoBearer: { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' },
    },
    schemas: {
      ApiError: {
        type: 'object',
        additionalProperties: false,
        required: ['code', 'message'],
        properties: {
          code: { type: 'string', pattern: '^[a-z][a-z0-9_]{0,63}$' },
          message: { type: 'string', minLength: 1, maxLength: 1000 },
        },
      },
    },
  },
}, null, 2)}\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(outputPath, 'utf8') !== output) {
    throw new Error('API contract output is stale. Run npm run contract:generate from services/API.');
  }
  if (readFileSync(swiftOutputPath, 'utf8') !== swiftOutput) {
    throw new Error('Swift API contract output is stale. Run npm run contract:generate from services/API.');
  }
  if (readFileSync(openApiOutputPath, 'utf8') !== openApi) {
    throw new Error('OpenAPI contract output is stale. Run npm run contract:generate from services/API.');
  }
} else {
  writeFileSync(outputPath, output);
  writeFileSync(openApiOutputPath, openApi);
  mkdirSync(dirname(swiftOutputPath), { recursive: true });
  writeFileSync(swiftOutputPath, swiftOutput);
}
